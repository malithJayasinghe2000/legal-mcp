"""Write docs/REVIEW-CHECKLIST.md: every rule grouped by its law, with the PDF page of its quote.

Run: uv run --group sources python scripts/review_checklist.py
Re-run after a rule's review_status changes; the ticks come from the rule files.
Needs the downloaded sources (sources/raw/) to find page numbers.
"""

import re
import unicodedata
from collections import defaultdict
from pathlib import Path

import yaml
from pypdf import PdfReader

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "REVIEW-CHECKLIST.md"
SEVERITY = {"must": "Must", "should": "Should", "lawyer": "Check with a lawyer"}
ORDER = {"must": 0, "should": 1, "lawyer": 2}

HEADER = """# Rule review checklist (owner review, brief D5)

Generated by `uv run --group sources python scripts/review_checklist.py`; don't edit by hand.
A box is ticked when the rule's `review_status` is no longer `draft`.

The test already proves every quote is word for word in the source. So you check meaning,
not spelling. For each rule, open the PDF at the page shown and ask:

1. **Section**: is the quote really in the section the rule names?
2. **Meaning**: do `why` and `what_to_do` say what the law says, with nothing added?
   Read a few lines before and after the quote (exceptions, "unless", "subject to").
3. **Severity**: Must = illegal without it; Should = real risk; Check with a lawyer = unclear.
4. **When it applies**: do the `triggers` fit? Too wide = noise, too narrow = a missed law.

Done? In the rule file set `review_status: checked_by_owner`, `reviewed_by: Malith Jayasinghe`
and `last_checked` to today. Unsure? Add the point to `lawyer_questions` instead of guessing.
"""


def norm(text: str) -> str:
    """Same as tests/test_rules.py: ignore PDF spacing, ligatures, dash and quote styles."""
    text = unicodedata.normalize("NFKC", text).lower()
    text = re.sub(r"[\u2010-\u2015\u2212]", "-", text)
    text = re.sub(r"[\u201c\u201d\u201e\u201f]", '"', text)
    text = re.sub(r"[\u2018\u2019\u201a\u201b]", "'", text)
    return re.sub(r"\s+", "", text)


def pdf_pages(source_id: str) -> list[str] | None:
    pdf = ROOT / "sources" / "raw" / f"{source_id}.pdf"
    if not pdf.exists():
        return None
    return [norm(p.extract_text() or "") for p in PdfReader(pdf).pages]


def find_page(pages: list[str] | None, quote: str) -> int | None:
    if not pages:
        return None
    start = norm(quote)[:60]
    for i, text in enumerate(pages):
        if start in text:
            return i + 1
    for i in range(len(pages) - 1):  # the start of the quote runs over a page break
        if start in pages[i] + pages[i + 1]:
            return i + 1
    return None


def main() -> None:
    sources = {s["id"]: s for s in yaml.safe_load((ROOT / "sources" / "sources.yaml").read_text())}
    by_source = defaultdict(list)
    for path in sorted((ROOT / "rules").glob("*/*.yaml")):
        rule = yaml.safe_load(path.read_text())
        by_source[rule["law"]["source_id"]].append((path, rule))

    def has_transcript(sid: str) -> bool:
        return (ROOT / "sources" / "transcripts" / f"{sid}.txt").exists()

    # Typed copies of scanned PDFs first (they need an extra check), then the biggest laws.
    order = sorted(by_source, key=lambda s: (not has_transcript(s), -len(by_source[s]), s))
    total = sum(len(v) for v in by_source.values())
    done = sum(r["review_status"] != "draft" for v in by_source.values() for _, r in v)

    out = [HEADER, f"**Progress: {done} of {total} rules checked.**\n"]
    for n, sid in enumerate(order, 1):
        rules = sorted(by_source[sid], key=lambda pr: (ORDER[pr[1]["severity"]], pr[1]["id"]))
        name = rules[0][1]["law"]["name"]
        url = sources[sid]["url"]
        out.append(f"## {n}. {name} ({len(rules)} rules)\n")
        out.append(f"Source: {url}\n")
        pages = None
        if has_transcript(sid):
            out.append(
                f"- [ ] **First:** this PDF is a scan. Quotes come from the typed copy "
                f"[sources/transcripts/{sid}.txt](../sources/transcripts/{sid}.txt). "
                "Compare it with the PDF, line by line.\n"
            )
        else:
            pages = pdf_pages(sid)
        for path, r in rules:
            tick = "x" if r["review_status"] != "draft" else " "
            law = r["law"]
            page = find_page(pages, law["quote"])
            where = f"[page {page}]({url}#page={page})" if page else "find it in the PDF"
            quote = " ".join(law["quote"].split())
            rel = path.relative_to(ROOT)
            out.append(
                f"- [{tick}] **{SEVERITY[r['severity']]}** - {r['title']}  \n"
                f"  `{law['section']}`, {where} - [{r['id']}](../{rel})  \n"
                f'  > "{quote}"\n'
            )
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}: {total} rules, {done} checked")


if __name__ == "__main__":
    main()
